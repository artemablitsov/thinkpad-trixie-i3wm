#!/usr/bin/env python3
"""Быстрые копии плагинов Oh My Zsh: kubectl, docker, gh, helm, uv.

usage: omz-fastplugins.py <~/.oh-my-zsh> <$ZSH_CUSTOM>

Эти плагины при КАЖДОМ запуске zsh в фоне заново генерируют файл автодополнения
(kubectl completion zsh, docker --version + docker completion, gh …, helm …,
uv …, uvx …) — шесть лишних процессов на каждое открытие терминала.

Скрипт кладёт в $ZSH_CUSTOM/plugins/<имя>/ копию плагина (Oh My Zsh берёт
плагин из custom раньше встроенного), где каждый такой фоновый блок обёрнут
в проверку `_cd_fresh <имя>` (функция из ~/.zshrc): генерация идёт, только если
файла нет, он пустой, старше недели или старше самой программы. Алиасы и всё
остальное остаются как в оригинале.

Если в новой версии Oh My Zsh блок не найден — копия не создаётся (и старая
удаляется): работает оригинальный плагин, ничего не ломается.
"""
import os
import re
import shutil
import sys

PLUGINS = ("kubectl", "docker", "gh", "helm", "uv")
MARK = "# cyberdeck: generated by lib/omz-fastplugins.py from the Oh My Zsh plugin\n"

omz, custom = sys.argv[1], sys.argv[2]


def transform(text):
    lines = text.split("\n")
    out, i, n = [], 0, 0
    while i < len(lines):
        m = re.match(r"^(\s*)\(\) \{\s*$", lines[i])
        if not m:
            out.append(lines[i]); i += 1; continue
        ind = m.group(1)
        # закрывающая строка блока — «}» с тем же отступом и запуском в фоне
        j = next((k for k in range(i + 1, len(lines))
                  if re.match(r"^%s\}.*&\|\s*$" % re.escape(ind), lines[k])), None)
        body = "\n".join(lines[i:j + 1]) if j else ""
        names = re.findall(r'completions/_(\w+)"', body)
        if j is None or not names or "zf_mv" not in body:
            out.append(lines[i]); i += 1; continue
        out.append("%s_cd_fresh %s || {" % (ind, names[-1]))
        out.extend(lines[i:j + 1])
        out.append("%s}" % ind)
        n += 1
        i = j + 1
    return "\n".join(out), n


for name in PLUGINS:
    src_dir = os.path.join(omz, "plugins", name)
    dst_dir = os.path.join(custom, "plugins", name)
    src = os.path.join(src_dir, name + ".plugin.zsh")
    dst = os.path.join(dst_dir, name + ".plugin.zsh")
    # своя (не сгенерированная) копия пользователя — не трогаем
    if os.path.exists(dst) and not open(dst).read().startswith(MARK):
        print("skip %s: own plugin in %s" % (name, dst_dir))
        continue
    try:
        text = open(src).read()
    except OSError:
        continue
    new, n = transform(text)
    if n == 0:
        shutil.rmtree(dst_dir, ignore_errors=True)
        print("skip %s: no background completion block found" % name)
        continue
    os.makedirs(dst_dir, exist_ok=True)
    tmp = dst + ".tmp"
    with open(tmp, "w") as f:
        f.write(MARK + new)
    os.replace(tmp, dst)
    # docker берёт запасной _docker из каталога плагина ("${0:A:h}/completions")
    if os.path.isdir(os.path.join(src_dir, "completions")):
        link = os.path.join(dst_dir, "completions")
        if os.path.islink(link):
            os.unlink(link)
        if not os.path.exists(link):
            os.symlink(os.path.join(src_dir, "completions"), link)
    print("%s: %d block(s)" % (name, n))
